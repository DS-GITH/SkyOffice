// Pixel art for the Xpert Office avatar generator (1x scale; the game draws it at 2x).
//
// Frame: 16 x 24 px. Head rows 0-14, torso 15-19, legs 19-23.
// Views: 'front' (facing down), 'back' (facing up), 'side' (facing right; left is mirrored).
//
// Every template is a list of rows. Characters are pixel ROLES, painted later with a ramp:
//   .  transparent        o  outline of the layer
//   skin:  s base  S shade  b blush  e eye  E eye (lower)  k hand  K hand shade
//   hair:  a base  A shade  l light  D deep  x hair tie
//   cloth: 1 base  2 shade  3 light  4 deep  u shoulder  v upper arm  w white  W white shade
//          x accent  X accent shade  k/K skin
//   glasses: f frame  g lens (tinted)  G dark lens  h lens shine

export type View = 'front' | 'back' | 'side'
export type Rows = string[]

/** Mirrors 8-char half rows into symmetric 16-char rows. */
export function sym(rows: Rows): Rows {
  return rows.map((r) => r + r.split('').reverse().join(''))
}

